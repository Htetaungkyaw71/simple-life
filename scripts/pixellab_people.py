"""Pack user-approved PixelLab exports without modifying source RGBA pixels."""
from pathlib import Path
from PIL import Image
import json

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'docs/assets/licenses/characters-pixellab/source/Idle'
ROWS = [('down', 'south'), ('up', 'north'), ('left', 'west'), ('right', 'east')]
SIZE, GROUND, SCALE = 48, 40, 2

def poses(direction):
    idle = Image.open(SOURCE / 'rotations' / (direction + '.png')).convert('RGBA')
    assert idle.size == (32, 32)
    padded = Image.new('RGBA', (SIZE, SIZE))
    padded.paste(idle, (8, 9))  # Shared ground row 40; preserve idle's native pixels.
    run = [Image.open(SOURCE / 'animations/Running' / direction / f'frame_{n:03d}.png').convert('RGBA') for n in range(8)]
    assert all(im.size == (SIZE, SIZE) for im in run)
    assert len({im.tobytes() for im in run}) == 8
    # Existing world jump arc uses real passing run poses, not a new jump animation.
    return [padded, *run, run[2], run[6], run[2]]

def grip(im, direction):
    side = -1 if direction in ('up', 'right') else 1
    skin = []
    for y in range(GROUND - 18, GROUND - 6):
        for x in range(SIZE):
            r, g, b, a = im.getpixel((x, y))
            if a == 255 and r > 120 and r > g * 1.25 and g > b * 1.25:
                skin.append((x, y))
    assert skin, direction
    preferred = [(x, y) for x, y in skin if (x - SIZE / 2) * side >= 1] or skin
    edge = max(x * side for x, y in preferred)
    candidates = [(x, y) for x, y in preferred if x * side == edge]
    x, y = candidates[len(candidates) // 2]
    return [(x - SIZE / 2) * SCALE + 1, (y - GROUND) * SCALE + 1]

def write_farmer():
    sheet = Image.new('RGBA', (SIZE * 12, SIZE * 4))
    hands = {}
    for row, (direction, exported) in enumerate(ROWS):
        frames = poses(exported)
        hands[direction] = [grip(im, direction) for im in frames]
        for f, im in enumerate(frames):
            sheet.paste(im, (f * SIZE, row * SIZE))
    sheet.save(ROOT / 'public/assets/pixel/processed/boy.png')
    (ROOT / 'src/data/farmerHands.js').write_text('// Source skin-pixel grips; generated by scripts/pixellab_people.py.\nexport const FARMER_HANDS=' + json.dumps(hands, separators=(',', ':')) + ';\n')
    return {'sourceRecord': 'docs/assets/licenses/characters-pixellab/SOURCE_RECORD.md', 'size': [48, 48], 'groundRow': 40, 'idleOffset': [8, 9], 'runFrames': 8, 'runFps': 16, 'sourcePixelsPreserved': True}

if __name__ == '__main__':
    print(json.dumps(write_farmer()))

"""Convert generated authored poses to a small local sprite atlas.

The original RGBA image is retained as evidence. This format conversion uses
nearest sampling and one shared palette, not invented cut-and-warp animation.
"""
from pathlib import Path
from PIL import Image
import hashlib
import json
from zipfile import ZipFile, ZIP_DEFLATED

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'docs/assets/licenses/farmer-girl-v1/source/generated-sheet.png'
SIZE, GROUND, SOURCE_SCALE = 48, 40, 6.5
DIRECTIONS = ['down', 'up', 'left', 'right']
X_RANGES = [(61,189),(274,398),(477,599),(687,805),(885,1009),(1089,1211),(1284,1415),(1486,1614),(1693,1816)]
Y_RANGES = [(14,212),(226,417),(431,622),(634,826)]

def grip(im,direction):
    side=-1 if direction in ('up','right') else 1
    # Bright tan pixels below the neckline. Brown hair highlights otherwise
    # resemble skin under the male export's broader colour threshold.
    skin=[]
    for y in range(25,34):
        for x in range(SIZE):
            r,g,b,a=im.getpixel((x,y))
            if a==255 and r>=180 and g>=110 and r>g*1.25 and g>b*1.25:
                skin.append((x,y))
    assert skin,direction
    preferred=[(x,y) for x,y in skin if (x-SIZE/2)*side>=1] or skin
    extreme=max(x*side for x,y in preferred)
    edge=[(x,y) for x,y in preferred if x*side==extreme]
    x,y=edge[len(edge)//2]
    return [(x-SIZE/2)*2+1,(y-GROUND)*2+1]

def native_poses():
    source = Image.open(SOURCE).convert('RGBA')
    assert source.size == (1881,836)
    frames = []
    anchors = []
    for y0, ground in Y_RANGES:
        row = []
        row_anchors = []
        for x0, x1 in X_RANGES:
            # Register at the torso/waist, so varying arm reach and ponytail
            # width cannot make the whole sprite drift during its cycle.
            waist = []
            for y in range(ground-86,ground-65):
                for x in range(x0,x1):
                    r,g,b,a = source.getpixel((x,y))
                    if a>=128 and 25<r<155 and g>=r*.86 and g>b*1.2:
                        waist.append(x)
            assert waist, (x0,y0)
            cx = round(sum(waist)/len(waist))
            cell = Image.new('RGBA',(312,312))
            # Isolate this pose before padding; adjacent rows must not leak
            # into a cell's otherwise transparent top and bottom gutters.
            pose = source.crop((x0,y0,x1,ground))
            cell.paste(pose,(round(x0-cx+156),round(y0-ground+260)))
            im = cell.resize((SIZE,SIZE),Image.Resampling.NEAREST)
            im.putdata([(*p[:3],255) if p[3]>=128 else (0,0,0,0) for p in im.get_flattened_data()])
            row.append(im);row_anchors.append([cx,ground])
        frames.append(row);anchors.append(row_anchors)
    # One stable 32-colour palette for all directions and animation phases.
    opaque = [p[:3] for row in frames for im in row for p in im.get_flattened_data() if p[3]]
    samples = Image.new('RGB',(len(opaque),1));samples.putdata(opaque)
    palette = samples.quantize(colors=32,method=Image.Quantize.MEDIANCUT)
    for row in frames:
        for i,im in enumerate(row):
            rgb = im.convert('RGB').quantize(palette=palette,dither=Image.Dither.NONE).convert('RGB')
            rgb.putalpha(im.getchannel('A'));row[i]=rgb
    return frames, anchors

def write_girl():
    frames, anchors = native_poses()
    sheet = Image.new('RGBA',(SIZE*12,SIZE*4));hands={}
    for r, direction in enumerate(DIRECTIONS):
        idle, *run = frames[r]
        assert len({im.tobytes() for im in run})==8, direction
        poses = [idle,*run,run[2],run[6],run[2]]
        hands[direction] = [grip(im,direction) for im in poses]
        for f, im in enumerate(poses):sheet.paste(im,(f*SIZE,r*SIZE))
    sheet.save(ROOT/'public/assets/pixel/processed/girl.png')
    (ROOT/'src/data/girlHands.js').write_text('// Native skin-pixel grips; generated by scripts/generated_girl.py.\nexport const GIRL_HANDS='+json.dumps(hands,separators=(',',':'))+';\n')
    sheet.save(ROOT/'output/art/farmer-girl-sprites-v1.png')
    preview = Image.new('RGBA',(48*9,48*4))
    for r,row in enumerate(frames):
        for f,im in enumerate(row):preview.paste(im,(48*f,48*r))
    preview.resize((48*9*4,48*4*4),Image.Resampling.NEAREST).save(ROOT/'output/art/farmer-girl-contact-v1.png')
    export = ROOT/'output/art/farmer-girl-v1';export.mkdir(parents=True,exist_ok=True)
    compass = ['south','north','west','east']
    for row,name in zip(frames,compass):
        (export/'idle').mkdir(exist_ok=True)
        row[0].crop((8,9,40,41)).save(export/'idle'/f'{name}.png')
        dest=export/'running'/name;dest.mkdir(parents=True,exist_ok=True)
        for f,im in enumerate(row[1:]):im.save(dest/f'frame_{f:03d}.png')
    sheet.save(export/'sprites.png')
    # Render the generated native frames into a four-direction preview.
    animation=[]
    for f in range(8):
        frame=Image.new('RGB',(48*4,48),(227,223,198))
        for r in range(4):frame.paste(frames[r][f+1],(r*48,0),frames[r][f+1])
        animation.append(frame.resize((48*4*3,48*3),Image.Resampling.NEAREST))
    animation[0].save(ROOT/'output/art/farmer-girl-running-v1.gif',save_all=True,append_images=animation[1:],duration=[60,60,70,60,60,70,60,60],loop=0)
    record = {'tool':'OpenAI built-in image_gen','sourceSha256':hashlib.sha256(SOURCE.read_bytes()).hexdigest(),'nativeSheetSha256':hashlib.sha256((ROOT/'public/assets/pixel/processed/girl.png').read_bytes()).hexdigest(),'sourceSize':[1881,836],'cellSize':[48,48],'visibleIdleHeights':[im[0].getbbox()[3]-im[0].getbbox()[1] for im in frames],'sourceScale':SOURCE_SCALE,'conversion':'nearest sampling, alpha threshold 128, shared 32-colour palette, waist registration','anchors':anchors,'directions':DIRECTIONS,'idleFramesPerDirection':1,'runFramesPerDirection':8,'runFps':16,'groundRow':GROUND,'jump':'Existing world arc uses passing run poses; no separately authored jump animation.'}
    (ROOT/'docs/assets/licenses/farmer-girl-v1/record.json').write_text(json.dumps(record,indent=2)+'\n')
    (export/'manifest.json').write_text(json.dumps(record,indent=2)+'\n')
    (export/'README.txt').write_text('Original OpenAI-generated farmer girl, adapted to native pixels with Codex assistance.\n4 idle PNGs: 32x32. 4 running directions: 8 PNGs each, 48x48, 16 fps.\nsprites.png: 12 columns x 4 rows of 48x48 cells; rows south/north/west/east.\nEach row: idle, 8 run frames, 3 repeated passing poses for the game jump arc.\nWorld foot anchor: x=24, y=40. Game scale: integer 2x, nearest filtering.\nOpenAI service output terms apply: https://openai.com/policies/terms-of-use/\nNot CC0 or a claim of exclusive copyright. Source/prompt/conversion evidence: docs/assets/licenses/farmer-girl-v1 in the project.\n')
    with ZipFile(ROOT/'output/art/farmer-girl-v1.zip','w',ZIP_DEFLATED) as z:
        for p in sorted(export.rglob('*')):
            if p.is_file():z.write(p,p.relative_to(export).as_posix())
    manifest=ROOT/'public/assets/pixel/processed/manifest.json'
    data=json.loads(manifest.read_text());data['characterFrames']['generatedGirl']=record
    manifest.write_text(json.dumps(data,indent=2)+'\n')
    return record

if __name__=='__main__':print(json.dumps(write_girl()))

"""Export approved proposal contours/config, preserving the historical preview.
Run from the repo root with the bundled Python/Pillow runtime.
Only City source data is written; no approved sprite PNG is edited.
"""
from pathlib import Path
from PIL import Image,ImageDraw,ImageChops
import json
root=Path.cwd();v3=root/'output/previews/city-road-layout-v3'
p=json.loads((v3/'proposal.json').read_text());old=json.loads((v3/'current-city.json').read_text())['map']
patches=[]
for a,b in zip(old['props'],p['proposedProps']):
 if (a['x'],a['y'])!=(b['x'],b['y']):
  row={'name':a['name'],'from':[a['x'],a['y']],'to':[b['x'],b['y']]}
  if 'previewTree' in a:row['treeVisual']=a['previewTree']
  if row['name']=='tree' and row['to']==[368,920]:row['to']=[360,920]
  if row['name']=='city-lamp' and row['to']==[320,282]:row['to']=[312,282]
  if row['name']=='city-lamp' and row['to']==[1048,282]:row['to']=[1056,282]
  patches.append(row)
# Keep two existing root footprints off the six-world-unit projected curb face.
a=next(a for a in old['props'] if a['name']=='tree' and [a['x'],a['y']]==[2332,1036])
patches.append({'name':'tree','from':[2332,1036],'to':[2332,1044],'treeVisual':a['previewTree']})
config={k:p[k] for k in ['roads','terrace','frontageStreet','curbHeightWorld','loweredCrossings','island','reservedFrontages']}
config['propMoves']=patches
config['planting']=[{k:v for k,v in a.items() if k in ['frame','x','y','foot','scale','kind','group']} for a in p['planting']]
(root/'src/data/cityLayout.js').write_text('// Approved City proposal 03. World coordinates; current game grass is retained.\nexport const CITY_LAYOUT='+json.dumps(config,separators=(',',':'))+';\n')
images={name:Image.open(v3/file).convert('L') for name,file in [('walk','pedestrian-mask.png'),('road','road-mask.png'),('cream','cream-mask.png'),('island','island-mask.png'),('ramp','lowered-crossings-mask.png')]}
# Real-game acceptance: keep the unchanged cottage feet and flowerpots on cream
# door aprons instead of letting the preview's broad road rectangles run beneath them.
parcel=Image.new('L',images['road'].size);d=ImageDraw.Draw(parcel)
for b in old['buildings']:
 x,y=b['x']//2,b['y']//2;d.rectangle((x,y,x+119,y+115),fill=255)
images['road']=ImageChops.subtract(images['road'],parcel)
images['cream']=ImageChops.subtract(images['walk'],images['road'])
masks={}
for name,im in images.items():
 start=0;previous=None;boxes=[]
 for y in range(im.height+1):
  runs=[]
  if y<im.height:
   a=list(im.crop((0,y,im.width,y+1)).get_flattened_data());x=0
   while x<im.width:
    if not a[x]:x+=1;continue
    end=x+1
    while end<im.width and a[end]:end+=1
    runs.append([x,end-x]);x=end
  if runs!=previous:
   if previous:boxes.extend([[x,start,w,y-start] for x,w in previous])
   previous=runs;start=y
 masks[name]=boxes
(root/'src/data/citySurfaceMasks.js').write_text('// Native-pixel contours from approved proposal 03, with clear cottage aprons.\n// Generated by scripts/export_city_layout.py; no scenery or reference pixels.\nexport const CITY_SURFACE_RECTS='+json.dumps(masks,separators=(',',':'))+';\n')
print('Exported City config and five contour masks.')

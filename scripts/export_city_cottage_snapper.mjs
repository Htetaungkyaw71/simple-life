// Install the user's native Pixel Snapper cottage without resizing its canvas.
import fs from 'node:fs';
import crypto from 'node:crypto';
import {PNG} from './prop_pixels.mjs';

const root=new URL('../',import.meta.url);
const path=name=>new URL(name,root);
const read=name=>fs.readFileSync(path(name));
const output='output/art/city-cottage-snapper-v2/';
const sourceBytes=read(output+'original-pixel-snapper.png');
const source=PNG.sync.read(sourceBytes);
if(source.width!==167||source.height!==110)throw Error('Expected the approved 167x110 Pixel Snapper source');

// Pixel Snapper supplied a fully opaque canvas. Remove only exact white backdrop
// pixels; keep every non-white source pixel and the native canvas dimensions.
const native=new PNG({width:source.width,height:source.height});
let removedWhite=0,retainedPixels=0;
for(let i=0;i<source.data.length;i+=4){
 const white=source.data[i]===255&&source.data[i+1]===255&&source.data[i+2]===255;
 if(white){native.data[i]=0;native.data[i+1]=0;native.data[i+2]=0;native.data[i+3]=0;removedWhite++;}
 else {source.data.copy(native.data,i,i,i+4);retainedPixels++;}
}
const nativeBytes=PNG.sync.write(native);
fs.writeFileSync(path(output+'native-transparent-167x110.png'),nativeBytes);

const before=PNG.sync.read(read(output+'before-town.png'));
const atlas=new PNG({width:before.width,height:before.height});
before.data.copy(atlas.data);
const x=774,y=3927,frame='city-review-cottage-terracotta-snapper';
if(x+native.width>atlas.width||y+native.height>atlas.height)throw Error('Cottage frame does not fit the reserved atlas strip');
for(let yy=0;yy<native.height;yy++)for(let xx=0;xx<native.width;xx++){
 const src=(yy*native.width+xx)*4,dst=((y+yy)*atlas.width+x+xx)*4;
 native.data.copy(atlas.data,dst,src,src+4);
}
fs.writeFileSync(path('public/assets/pixel/processed/town.png'),PNG.sync.write(atlas));

const meta=JSON.parse(read(output+'before-town.json'));
meta.frames[frame]={frame:{x,y,w:native.width,h:native.height},rotated:false,trimmed:false,spriteSourceSize:{x:0,y:0,w:native.width,h:native.height},sourceSize:{w:native.width,h:native.height}};
fs.writeFileSync(path('public/assets/pixel/processed/town.json'),JSON.stringify(meta,null,2)+'\n');

let x0=native.width,y0=native.height,x1=-1,y1=-1;
const rows=[];let previous=null,start=0;
for(let yy=0;yy<=native.height;yy++){
 const ink=[];
 for(let xx=0;xx<native.width&&yy<native.height;xx++)if(native.data[(yy*native.width+xx)*4+3])ink.push(xx);
 const run=ink.length?[Math.min(...ink),Math.max(...ink)-Math.min(...ink)+1]:null;
 if(run){x0=Math.min(x0,run[0]);x1=Math.max(x1,run[0]+run[1]-1);y0=Math.min(y0,yy);y1=Math.max(y1,yy);}
 if(JSON.stringify(run)!==JSON.stringify(previous)){
  if(previous)rows.push([previous[0]*2,start*2,previous[1]*2,(yy-start)*2]);
  previous=run;start=yy;
 }
}
// Preserve the established door/porch world anchor while accounting for the
// source canvas's transparent left/top margin.
const art={frame,width:native.width,height:native.height,scale:2,bounds:[x0,y0,x1+1,y1+1],solidRows:rows,originOffset:[-40,22],doorOffset:[166,200]};
fs.writeFileSync(path('src/data/cityCottageArt.js'),'// User-approved Pixel Snapper cottage; generated by scripts/export_city_cottage_snapper.mjs.\nexport const CITY_COTTAGE_ART='+JSON.stringify(art)+';\n');

const sha=bytes=>crypto.createHash('sha256').update(bytes).digest('hex');
let preExistingPixelsExact=true;
for(let yy=0;yy<before.height;yy++)for(let xx=0;xx<before.width;xx++)if(xx<x||xx>=x+native.width||yy<y||yy>=y+native.height){
 const i=(yy*before.width+xx)*4;for(let c=0;c<4;c++)if(before.data[i+c]!==atlas.data[i+c])preExistingPixelsExact=false;
}
const audit={source:{path:output+'original-pixel-snapper.png',sha256:sha(sourceBytes),dimensions:[source.width,source.height],alpha:[...new Set(source.data.filter((_,i)=>i%4===3))]},native:{path:output+'native-transparent-167x110.png',sha256:sha(nativeBytes),dimensions:[native.width,native.height],binaryAlpha:[...new Set(native.data.filter((_,i)=>i%4===3))].sort((a,b)=>a-b),removedWhite,retainedPixels,nonWhitePixelsExact:true,worldScale:2},atlas:{dimensions:[atlas.width,atlas.height],frame,position:[x,y],preExistingPixelsExact}};
fs.writeFileSync(path(output+'art-audit.json'),JSON.stringify(audit,null,2)+'\n');
console.log(JSON.stringify({frame,bounds:art.bounds,originOffset:art.originOffset,doorOffset:art.doorOffset,removedWhite,retainedPixels,solidRows:rows.length,atlas:[atlas.width,atlas.height]},null,2));

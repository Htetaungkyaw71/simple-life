"""Add only the approved shop aprons to the preserved proposal contours."""
from pathlib import Path
from PIL import Image,ImageDraw,ImageChops
import json
root=Path.cwd();source=root/'output/previews/city-garden-shops-v2'
p=json.loads((source/'proposal.json').read_text())
images={n:Image.open(source/'evidence'/f'{n}-mask.png').convert('RGBA').getchannel('A') for n in ['walk','road','cream','island','ramp']}
images['placementWalk']=images['walk'].copy()
extra=Image.new('L',images['walk'].size);d=ImageDraw.Draw(extra)
for x,y,w,h in p['pavedExtensions']:d.rounded_rectangle((x//2,y//2,(x+w)//2-1,(y+h)//2-1),radius=6,fill=255)
for n in ['walk','cream']:images[n]=ImageChops.lighter(images[n],extra)
images['road']=ImageChops.subtract(images['road'],extra)
masks={}
for name,im in images.items():
 start=0;previous=None;boxes=[]
 for y in range(im.height+1):
  runs=[]
  if y<im.height:
   a=list(im.crop((0,y,im.width,y+1)).get_flattened_data());x=0
   while x<im.width:
    if not a[x]:x+=1;continue
    end=x+1
    while end<im.width and a[end]:end+=1
    runs.append([x,end-x]);x=end
  if runs!=previous:
   if previous:boxes.extend([[x,start,w,y-start] for x,w in previous])
   previous=runs;start=y
 masks[name]=boxes
(root/'src/data/citySurfaceMasks.js').write_text('// Approved City contours plus shop proposal 02 aprons. Native pixels, 2 world units each.\n// Generated by scripts/export_city_shop_surfaces.py.\nexport const CITY_SURFACE_RECTS='+json.dumps(masks,separators=(',',':'))+';\n')
print('Exported approved shop aprons.')
